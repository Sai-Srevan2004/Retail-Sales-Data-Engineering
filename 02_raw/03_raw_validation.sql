USE DATABASE RETAIL_SUPPLY_CHAIN;

--======================================================
--1. VALIDATION OF NO OF RECORDS LOADED INTO RAW 
--======================================================

SELECT
    'CUSTOMERS' AS ENTITY,
    COUNT(*) AS TOTAL_ROWS
FROM RAW.CUSTOMERS

UNION ALL

SELECT
    'PRODUCTS' AS ENTITY,
    COUNT(*) AS TOTAL_ROWS
FROM RAW.PRODUCTS

UNION ALL

SELECT
    'STORES' AS ENTITY,
    COUNT(*) AS TOTAL_ROWS
FROM RAW.STORES

UNION ALL

SELECT
    'SALES' AS ENTITY,
    COUNT(*) AS TOTAL_ROWS
FROM RAW.SALES

ORDER BY ENTITY;

