USE DATABASE RETAIL_SUPPLY_CHAIN;

--===================================================
--ROOT TASK
--===================================================

CREATE OR REPLACE TASK CONTROL.TASK_PIPELINE_ROOT
    WAREHOUSE = RETAIL_WH
    WHEN
        SYSTEM$STREAM_HAS_DATA('RETAIL_SUPPLY_CHAIN.RAW.CUSTOMERS_STREAM')
        OR SYSTEM$STREAM_HAS_DATA('RETAIL_SUPPLY_CHAIN.RAW.PRODUCTS_STREAM')
        OR SYSTEM$STREAM_HAS_DATA('RETAIL_SUPPLY_CHAIN.RAW.SALES_STREAM')
AS
    SELECT 1;

--===================================================
--SILVER TASKS
--===================================================


CREATE OR REPLACE TASK CONTROL.TASK_SILVER_CUSTOMERS
    WAREHOUSE = RETAIL_WH
    AFTER CONTROL.TASK_PIPELINE_ROOT
AS
    CALL SILVER.LOAD_SILVER_CUSTOMERS();


CREATE OR REPLACE TASK CONTROL.TASK_SILVER_PRODUCTS
    WAREHOUSE = RETAIL_WH
    AFTER CONTROL.TASK_PIPELINE_ROOT
AS
    CALL SILVER.LOAD_SILVER_PRODUCTS();


CREATE OR REPLACE TASK CONTROL.TASK_SILVER_SALES
    WAREHOUSE = RETAIL_WH
    AFTER CONTROL.TASK_PIPELINE_ROOT
AS
    CALL SILVER.LOAD_SILVER_SALES();

--===================================================
--GOLD TASKS
--===================================================


CREATE OR REPLACE TASK CONTROL.TASK_GOLD_DIM_CUSTOMER
    WAREHOUSE = RETAIL_WH
    AFTER CONTROL.TASK_SILVER_CUSTOMERS
AS
    CALL GOLD.LOAD_GOLD_DIM_CUSTOMER();


CREATE OR REPLACE TASK CONTROL.TASK_GOLD_DIM_PRODUCT
    WAREHOUSE = RETAIL_WH
    AFTER CONTROL.TASK_SILVER_PRODUCTS
AS
    CALL GOLD.LOAD_GOLD_DIM_PRODUCT();


CREATE OR REPLACE TASK CONTROL.TASK_GOLD_FACT_SALES
    WAREHOUSE = RETAIL_WH
    AFTER
        CONTROL.TASK_GOLD_DIM_CUSTOMER,
        CONTROL.TASK_GOLD_DIM_PRODUCT,
        CONTROL.TASK_SILVER_SALES
AS
    CALL GOLD.LOAD_GOLD_FACT_SALES();


--===================================================
--RESUME TASKS
--===================================================


ALTER TASK CONTROL.TASK_GOLD_FACT_SALES RESUME;

ALTER TASK CONTROL.TASK_GOLD_DIM_CUSTOMER RESUME;
ALTER TASK CONTROL.TASK_GOLD_DIM_PRODUCT RESUME;

ALTER TASK CONTROL.TASK_SILVER_CUSTOMERS RESUME;
ALTER TASK CONTROL.TASK_SILVER_PRODUCTS RESUME;
ALTER TASK CONTROL.TASK_SILVER_SALES RESUME;

ALTER TASK CONTROL.TASK_PIPELINE_ROOT RESUME;

--===================================================
--CHECK TASKS
--===================================================

SHOW TASKS IN SCHEMA RETAIL_SUPPLY_CHAIN.CONTROL;
